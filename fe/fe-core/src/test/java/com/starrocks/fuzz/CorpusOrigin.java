package com.starrocks.fuzz;

/**
 * Where a corpus file came from: harvested from a real cluster, or generated by this fuzzer.
 *
 * <p>The distinction is the whole value of the production corpora. Their shapes are ones users
 * actually ran; a mutant's shapes are ones the mutator invented. Both are worth fuzzing and they
 * are not interchangeable, and the moment emitted corpora are fed back as input -- which is exactly
 * what {@code mut_NNN.novel.sql} exists for -- a run's input becomes a mixture of the two with no
 * way to tell the parts apart.
 *
 * <p>That mixture is the drift the splice pool is bounded to prevent, arriving by another route.
 * A bound on the pool does nothing if generation N's output is handed back as generation N+1's
 * input and nobody notices it happened.
 *
 * <h3>Both sides are stamped, not just one</h3>
 *
 * <p>Marking only generated files would make "no marker" mean three different things: harvested,
 * generated-but-stripped-by-a-copy, and hand-written. An absence is weak evidence and it is the
 * kind that silently decays -- concatenate two corpora and the header of the second is now in the
 * middle of the first. Harvested corpora carry {@code srfuzz-generation: 0}, so an unmarked file is
 * a file whose origin nobody recorded, which is a different and reportable state.
 *
 * <h3>The root matters more than the parent</h3>
 *
 * <p>{@code corpus-file:} names the immediate parent, which is enough for one hop and useless after
 * the intermediate is deleted or moved -- and intermediates are round output, so they are deleted
 * routinely. The root travels down every generation unchanged, so a statement five generations deep
 * still names the production cluster its ancestry started at.
 */
public final class CorpusOrigin {

    /** Header keys. Written as SQL line comments, which CorpusReader and mysql both skip. */
    private static final String ORIGIN = "-- srfuzz-origin:";
    private static final String GENERATION = "-- srfuzz-generation:";
    private static final String ROOT = "-- srfuzz-root:";

    /** How many header lines to scan before giving up; the stamp belongs at the top of the file. */
    private static final int SCAN_LINES = 40;

    public static final String HARVESTED = "harvested";
    public static final String GENERATED = "generated";
    /** Neither stamp present: not a claim that it is harvested, only that nobody said. */
    public static final String UNKNOWN = "unknown";

    private final String origin;
    private final int generation;
    private final String root;

    private CorpusOrigin(String origin, int generation, String root) {
        this.origin = origin;
        this.generation = generation;
        this.root = root;
    }

    public String origin() {
        return origin;
    }

    /** 0 for a harvested corpus, parent + 1 for anything this fuzzer emitted. */
    public int generation() {
        return generation;
    }

    /** The generation-0 corpus this file descends from, or {@link #UNKNOWN}. */
    public String root() {
        return root;
    }

    /** True when the file carries no stamp at all. */
    public boolean isUnknown() {
        return UNKNOWN.equals(origin);
    }

    /**
     * Reads the stamp off a corpus file's text.
     *
     * <p>Lenient by design: a corpus that predates stamping still has to run, so a missing or
     * malformed header yields {@link #UNKNOWN} rather than an exception. What it must never do is
     * quietly report {@code harvested} for a file nobody stamped -- that would launder generated
     * shapes into the production count, which is the one number this class exists to protect.
     */
    public static CorpusOrigin read(String text) {
        String origin = UNKNOWN;
        int generation = -1;
        String root = UNKNOWN;
        int seen = 0;
        for (String line : text.split("\n", SCAN_LINES + 1)) {
            if (++seen > SCAN_LINES) {
                break;
            }
            String t = line.trim();
            if (t.startsWith(ORIGIN)) {
                origin = t.substring(ORIGIN.length()).trim();
            } else if (t.startsWith(GENERATION)) {
                try {
                    generation = Integer.parseInt(t.substring(GENERATION.length()).trim());
                } catch (NumberFormatException ignored) {
                    // A malformed generation is an unstamped file, not a fatal error.
                }
            } else if (t.startsWith(ROOT)) {
                root = t.substring(ROOT.length()).trim();
            }
        }
        if (UNKNOWN.equals(origin) && generation < 0) {
            return new CorpusOrigin(UNKNOWN, -1, root);
        }
        // A file that says it is harvested but not which generation is generation 0 by definition.
        if (generation < 0) {
            generation = HARVESTED.equals(origin) ? 0 : 1;
        }
        return new CorpusOrigin(origin, generation, root);
    }

    /**
     * The stamp for a file this fuzzer is emitting, one generation on from {@code parent}.
     *
     * <p>The root is inherited, and only invented when the parent has none -- otherwise every
     * generation would rename the ancestry after its immediate parent and the lineage would say
     * nothing beyond one hop.
     */
    public static String stampFor(CorpusOrigin parent, String parentName) {
        int generation = parent == null || parent.generation() < 0 ? 1 : parent.generation() + 1;
        String root = parent == null || UNKNOWN.equals(parent.root()) ? parentName : parent.root();
        return ORIGIN + " " + GENERATED + "\n"
                + GENERATION + " " + generation + "\n"
                + ROOT + " " + root + "\n";
    }

    /** The stamp for a corpus harvested from a real cluster. */
    public static String harvestedStamp(String name) {
        return ORIGIN + " " + HARVESTED + "\n"
                + GENERATION + " 0\n"
                + ROOT + " " + name + "\n";
    }
}
